#!/usr/bin/env python3
"""
Generate a root .env with fresh random secrets for docker compose. Standard library only.

    python scripts/generate_env.py                       # localhost, port 8080
    python scripts/generate_env.py --host iam.example.com --https
    python scripts/generate_env.py --force               # overwrite an existing .env (rotates ALL secrets!)

WARNING: rotating VALIDATOR_PRIVATE_KEY on an existing deployment means new blocks are signed with a key
older blocks were not signed with. Back up the old .env and add the old public key to
EXTRA_VALIDATOR_PUBLIC_KEYS (see docs/PRODUCTION_READINESS.md, "Key rotation").
"""

import argparse
import base64
import os
import secrets
import stat
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--host", default="localhost", help="Public hostname users will browse to (default: localhost)")
    ap.add_argument("--port", default="8080", help="Host port for the web entrypoint (default: 8080)")
    ap.add_argument("--https", action="store_true", help="Site is served over TLS: enables secure cookies, HSTS, redirects")
    ap.add_argument("--proxies", default=None, help="Reverse proxies in front of Django (default 1, or 2 with --https)")
    ap.add_argument("--force", action="store_true", help="Overwrite an existing .env")
    args = ap.parse_args()

    target = ROOT / ".env"
    if target.exists() and not args.force:
        print(f"{target} already exists. Use --force to overwrite (this rotates every secret).", file=sys.stderr)
        return 1

    hosts = {"localhost", "127.0.0.1", args.host}
    scheme = "https" if args.https else "http"
    origin = f"{scheme}://{args.host}" + ("" if args.https or args.port == "80" else f":{args.port}")
    values = {
        "# --- web entrypoint ---": None,
        "WEB_PORT": args.port,
        "DJANGO_ALLOWED_HOSTS": ",".join(sorted(hosts)),
        "DJANGO_CSRF_TRUSTED_ORIGINS": origin,
        "DJANGO_HTTPS": str(args.https),
        "NUM_PROXIES": args.proxies or ("2" if args.https else "1"),
        "# --- PostgreSQL ---": None,
        "POSTGRES_DB": "secureaccess_iam",
        "POSTGRES_USER": "secureaccess",
        "POSTGRES_PASSWORD": secrets.token_urlsafe(32),
        "# --- MongoDB ---": None,
        "MONGO_USER": "ledger",
        "MONGO_PASSWORD": secrets.token_urlsafe(32),
        "# --- Django ---": None,
        "DJANGO_SECRET_KEY": secrets.token_urlsafe(60),
        "API_DOCS_ENABLED": "True",
        "GUNICORN_WORKERS": "2",
        "# --- Ledger: shared API key + this node's Ed25519 signing key (base64 of 32 random bytes) ---": None,
        "LEDGER_API_KEY": secrets.token_urlsafe(40),
        "VALIDATOR_ID": "node-1",
        "VALIDATOR_PRIVATE_KEY": base64.b64encode(os.urandom(32)).decode(),
        "# --- First administrator (optional; REMOVE ADMIN_PASSWORD after the first start) ---": None,
        "ADMIN_USERNAME": "",
        "ADMIN_EMAIL": "",
        "ADMIN_PASSWORD": "",
    }
    lines = ["# Generated by scripts/generate_env.py. NEVER commit this file; back it up somewhere safe."]
    for key, value in values.items():
        lines.append(f"\n{key}" if value is None else f"{key}={value}")
    target.write_text("\n".join(lines) + "\n")
    target.chmod(stat.S_IRUSR | stat.S_IWUSR)  # 0600
    print(f"Wrote {target} (permissions 600).")
    print(f"Site URL: {origin}")
    print("Next: docker compose up -d --build   then   docker compose exec identity_service python manage.py create_admin")
    return 0


if __name__ == "__main__":
    sys.exit(main())
